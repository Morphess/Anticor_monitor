"""Saved-report filtering and cross-session persistence in disposable PostgreSQL."""
import os
import unittest
from types import SimpleNamespace
from unittest.mock import patch
from sqlalchemy import create_engine, text
from sqlalchemy.orm import Session
from app.schemas.orders import OrderAnalysisRead
from app.repositories.execution_analysis_repository import ExecutionAnalysisRepository
from app.services.order_analysis_services import analysis_fingerprint
from app.core.config import settings


class AnalysisFingerprintTests(unittest.TestCase):
    def setUp(self):
        self.order = SimpleNamespace(number="SYNTHETIC", title="Test", issued_on=None)
        self.measure = SimpleNamespace(description="Training", deadline_on=None,
            deadline_description="Ongoing", completion_indicator="One training", required_evidence="Report")

    def test_target_or_model_changes_invalidate_cached_report(self):
        original = analysis_fingerprint(self.order, self.measure)
        self.measure.description = "Different training"
        self.assertNotEqual(original, analysis_fingerprint(self.order, self.measure))
        self.measure.description = "Training"
        with patch("app.services.order_analysis_services.settings", settings.model_copy(update={"OLLAMA_MODEL":"different-model"})):
            self.assertNotEqual(original, analysis_fingerprint(self.order, self.measure))
        with patch("app.services.order_analysis_services.settings", settings.model_copy(update={"OLLAMA_NUM_PREDICT":256})):
            self.assertNotEqual(original, analysis_fingerprint(self.order, self.measure))

    def test_waiting_budget_does_not_invalidate_completed_report(self):
        original = analysis_fingerprint(self.order, self.measure)
        with patch("app.services.order_analysis_services.settings", settings.model_copy(update={"OLLAMA_TIMEOUT_SECONDS":900})):
            self.assertEqual(original, analysis_fingerprint(self.order, self.measure))


@unittest.skipUnless(os.environ.get("ORDER_TEST_DATABASE_URL"), "Disposable PostgreSQL URL not supplied")
class AnalysisPersistencePostgresTests(unittest.TestCase):
    def setUp(self):
        self.engine = create_engine(os.environ["ORDER_TEST_DATABASE_URL"])
        self.conn = self.engine.connect()
        self.addCleanup(self.engine.dispose)
        self.addCleanup(self.conn.close)
        # Session-local table: no production fixtures or public rows are edited.
        self.conn.execute(text('''CREATE TEMP TABLE execution_analyses (
            analysis_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            execution_id integer NOT NULL, order_id varchar(50) NOT NULL,
            order_version_id integer NOT NULL, submitted_sha256 varchar(64) NOT NULL,
            input_sha256 varchar(64) NOT NULL, created_by_user_id integer,
            model varchar(200) NOT NULL, file_name varchar(255) NOT NULL,
            analysis text NOT NULL, text_truncated boolean NOT NULL,
            output_truncated boolean NOT NULL,
            created_at timestamptz NOT NULL DEFAULT clock_timestamp()
        )'''))
        self.conn.commit()
        self.result = OrderAnalysisRead(order_id="O1", file_name="synthetic.pdf", model="synthetic-model",
                                       analysis="Saved synthetic report", text_truncated=False)

    def test_report_survives_new_session_and_requires_exact_inputs(self):
        with Session(self.conn) as db:
            saved = ExecutionAnalysisRepository(db).save(11, 3, "a"*64, "b"*64, 7, self.result)
            identity = saved.analysis_id
        with Session(self.conn) as db:
            repo = ExecutionAnalysisRepository(db)
            saved = repo.latest(11, 3, "a"*64, "b"*64)
            self.assertEqual(saved.analysis_id, identity)
            self.assertEqual(saved.analysis, "Saved synthetic report")
            self.assertIsNotNone(saved.created_at)
            for args in ((12,3,"a"*64,"b"*64), (11,4,"a"*64,"b"*64),
                         (11,3,"c"*64,"b"*64), (11,3,"a"*64,"d"*64)):
                self.assertIsNone(repo.latest(*args))

    def test_repeat_keeps_history_and_returns_latest_report(self):
        with Session(self.conn) as db:
            repo = ExecutionAnalysisRepository(db)
            first_id = repo.save(11, 3, "a"*64, "b"*64, 7, self.result).analysis_id
            second_id = repo.save(11, 3, "a"*64, "b"*64, 7, self.result).analysis_id
            self.assertGreater(second_id, first_id)
            self.assertEqual(repo.latest(11,3,"a"*64,"b"*64).analysis_id, second_id)
            self.assertEqual(db.scalar(text("SELECT count(*) FROM execution_analyses")), 2)

    def test_transaction_lock_blocks_duplicate_generation_and_releases(self):
        with Session(self.conn) as first, Session(self.engine) as second:
            self.assertTrue(ExecutionAnalysisRepository(first).try_lock(12345))
            self.assertFalse(ExecutionAnalysisRepository(second).try_lock(12345))
            first.rollback()
            self.assertTrue(ExecutionAnalysisRepository(second).try_lock(12345))
            second.rollback()
